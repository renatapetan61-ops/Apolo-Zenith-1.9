from __future__ import annotations

import hashlib
import random
from pathlib import Path
from typing import List, Tuple


def file_sha256(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def split_text_corpus(text: str, train_frac: float = 0.9) -> Tuple[str, str]:
    """Split a raw corpus into train/holdout chunks by line."""
    lines = [ln for ln in text.splitlines() if ln.strip()]
    cut = int(len(lines) * train_frac)
    return "\n".join(lines[:cut]), "\n".join(lines[cut:])


class TextDataset:
    """In-memory tokenized LM dataset: yields (inputs, targets) windows.

    Every sample is a contiguous [seq_len] window of token ids; targets are
    the same window shifted by one (next-token prediction).
    """

    def __init__(self, token_ids: List[int], seq_len: int):
        assert seq_len >= 1
        self.ids = token_ids
        self.seq_len = seq_len
        self.num_windows = max(0, len(self.ids) - seq_len - 1)

    def __len__(self) -> int:
        return self.num_windows

    def __getitem__(self, i: int):
        chunk = self.ids[i : i + self.seq_len + 1]
        x = chunk[:-1]
        y = chunk[1:]
        assert len(x) == self.seq_len and len(y) == self.seq_len
        return x, y

    @classmethod
    def from_file(cls, path: str | Path, tokenizer, seq_len: int) -> "TextDataset":
        text = Path(path).read_text(encoding="utf-8")
        return cls(tokenizer.encode(text), seq_len)

    def loader(self, batch_size: int, shuffle: bool, seed: int,
               generator=None):
        """Yield batches of [B, seq_len] LongTensors (x and y)."""
        import torch
        idx = list(range(len(self)))
        g = generator or torch.Generator().manual_seed(seed)
        if shuffle:
            random.Random(seed).shuffle(idx)
        for s in range(0, len(idx), batch_size):
            batch = [self.__getitem__(idx[j]) for j in idx[s : s + batch_size]]
            xs = torch.tensor([b[0] for b in batch], dtype=torch.long)
            ys = torch.tensor([b[1] for b in batch], dtype=torch.long)
            yield xs, ys
